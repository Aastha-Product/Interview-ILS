// Pathfinder (private accounts): prints SQL that makes every link between two students' tables
// stay within one student. Each foreign key like Note.applicationId -> Application.id gets a twin
// on (userId, applicationId) -> Application(userId, id), with the same delete rule, so the
// database refuses a row that points at another student's row. Links to Theme are left out:
// built-in themes have no owner and every student may use them.
//
//   node scripts/owner-links-migration.mjs > prisma/migrations/<timestamp>_owner_links/migration.sql
import fs from "node:fs";

const schema = fs.readFileSync(new URL("../prisma/schema.prisma", import.meta.url), "utf8").replace(/\r\n/g, "\n");
const models = [...schema.matchAll(/^model (\w+) \{([\s\S]*?)^\}/gm)].map(([, name, body]) => ({ name, body }));
const owned = new Set(models.filter((m) => /^\s+userId\s+String\b/m.test(m.body)).map((m) => m.name));

const links = [];
for (const { name, body } of models) {
  if (!owned.has(name)) continue;
  for (const [, field, target, rel] of body.matchAll(/^\s+(\w+)\s+(\w+)\??\s+@relation\(([^)]*)\)/gm)) {
    if (target === "User" || target === "Theme" || !owned.has(target)) continue;
    const column = rel.match(/fields: \[(\w+)\]/)?.[1];
    if (!column || rel.match(/references: \[(\w+)\]/)?.[1] !== "id") throw new Error(`Unexpected relation ${name}.${field}`);
    const onDelete = rel.match(/onDelete: (\w+)/)?.[1] ?? "Restrict";
    links.push({ name, field, target, column, onDelete });
  }
}

const rule = { Cascade: "CASCADE", Restrict: "RESTRICT", NoAction: "NO ACTION" };
const out = [
  "-- Pathfinder (private accounts): links between a student's rows can't point at another student's",
  "-- rows. Generated by scripts/owner-links-migration.mjs; Prisma's schema doesn't describe these",
  "-- constraints, so a future `prisma migrate diff` will offer to drop them. Keep them.",
  "",
];
for (const target of [...new Set(links.map((l) => l.target))].sort()) {
  out.push(`CREATE UNIQUE INDEX "${target}_userId_id_key" ON "${target}"("userId", "id");`);
}
out.push("");
for (const l of links) {
  const del = l.onDelete === "SetNull" ? `SET NULL ("${l.column}")` : rule[l.onDelete];
  if (!del) throw new Error(`No delete rule for ${l.onDelete}`);
  out.push(
    `ALTER TABLE "${l.name}" ADD CONSTRAINT "${l.name}_${l.field}_same_owner_fkey" FOREIGN KEY ("userId", "${l.column}") ` +
      `REFERENCES "${l.target}"("userId", "id") ON DELETE ${del} ON UPDATE CASCADE;`,
  );
}
process.stdout.write(out.join("\n") + "\n");
